# Pre-build: write src/wifi_secrets.h (gitignored) from secrets/symphony.sops.yaml,
# so WiFi credentials never live in git in the clear and nobody hand-edits a header.
# Networks are tried in order by the device; whichever is in range wins.
Import("env")  # noqa: F821 -- SCons injects this
import re
import subprocess
from pathlib import Path

root = Path(env.subst("$PROJECT_DIR")).parents[1]  # noqa: F821
secrets = root / "secrets" / "symphony.sops.yaml"
header = Path(env.subst("$PROJECT_DIR")) / "src" / "wifi_secrets.h"  # noqa: F821


def sops_field(key):
    try:
        r = subprocess.run(
            ["sops", "-d", "--extract", f'["{key}"]', str(secrets)],
            capture_output=True, text=True)
    except FileNotFoundError:
        print("wifi_from_sops: sops not on PATH")
        return None
    if r.returncode != 0:
        print(f"wifi_from_sops: {key}: {r.stderr.strip().splitlines()[-1:] or 'sops failed'}")
        return None
    return r.stdout.rstrip("\n")


def keyfile(key):
    text = sops_field(key)
    if not text:
        return None
    ssid, psk = (re.search(rf"(?m)^{f}=(.*)$", text) for f in ("ssid", "psk"))
    return (ssid.group(1), psk.group(1)) if ssid and psk else None


home = (sops_field("home_wifi_ssid"), sops_field("home_wifi_password"))
networks = [
    home if all(home) else None,                  # home first: the bench is at home
    keyfile("nm_symphony_nmconnection"),          # the boat's 2.4 GHz network
]
networks = [n for n in networks if n]

if not networks:
    print("wifi_from_sops: no networks from sops; leaving src/wifi_secrets.h as is")
else:
    q = lambda s: '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    body = ", ".join(f"{{{q(s)}, {q(p)}}}" for s, p in networks)
    text = f"// Generated by wifi_from_sops.py; do not edit.\n#define WIFI_NETWORKS {{{body}}}\n"
    if not header.exists() or header.read_text() != text:
        header.write_text(text)
    print(f"wifi_from_sops: seeded {len(networks)} network(s)")
